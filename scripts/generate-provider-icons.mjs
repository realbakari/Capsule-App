#!/usr/bin/env node
/*
 * Vendors the provider marks the composer's agent picker draws.
 *
 * Capsule reaches seventeen ACP harnesses. Seven of them have a mark in the
 * simple-icons set (CC0-1.0), and hand-copying path data is how it goes stale,
 * so this writes the generated module instead. The other ten keep the monogram
 * tile — an invented logo would misidentify the product it stands for.
 *
 * Run with: pnpm icons:providers
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as icons from "simple-icons";

/** Harness id → the icon export that actually stands for that product. */
const MARKS = {
  // The burst, not the CLI's blocky tile: it stays legible at 16px.
  claude: "siClaude",
  copilot: "siGithubcopilot",
  cursor: "siCursor",
  gemini: "siGooglegemini",
  kimi: "siKimi",
  opencode: "siOpencode",
  qwen: "siQwen",
  trae: "siTrae",
};

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "apps/desktop/src/renderer/src/lib/provider-marks.ts");

const entries = Object.entries(MARKS).map(([id, key]) => {
  const icon = icons[key];
  if (!icon) throw new Error(`No icon named ${key}. Check the export list before regenerating.`);
  return { id, title: icon.title, hex: `#${icon.hex.toLowerCase()}`, path: icon.path };
});

const body = entries
  .map(
    (entry) =>
      `  ${JSON.stringify(entry.id)}: {\n` +
      `    title: ${JSON.stringify(entry.title)},\n` +
      `    hex: ${JSON.stringify(entry.hex)},\n` +
      `    path: ${JSON.stringify(entry.path)},\n` +
      `  },`,
  )
  .join("\n");

writeFileSync(
  out,
  `/*
 * Generated by scripts/generate-provider-icons.mjs. Do not edit by hand.
 *
 * Marks for the agent providers, on a 24x24 viewBox. The trademarks belong to
 * the products they identify; they appear here to name the agent Capsule is
 * talking to, nothing more.
 */

export interface ProviderMark {
  title: string;
  /** The brand colour, used only where it stays legible on Capsule's surface. */
  hex: string;
  /** Path data for a 24x24 viewBox. */
  path: string;
}

export const PROVIDER_MARKS: Record<string, ProviderMark> = {
${body}
};
`,
  "utf8",
);
console.log(`Wrote ${entries.length} marks to ${path.relative(root, out)}`);
