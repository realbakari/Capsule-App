#!/usr/bin/env node
/*
 * Vendors the provider marks the composer's agent picker draws.
 *
 * Capsule reaches seventeen ACP harnesses. Hand-copying path data is how a
 * logo goes stale and wrong, so the marks are generated from the MIT-licensed
 * @lobehub/icons-static-svg set (Copyright (c) LobeHub) into one module. The
 * harnesses with no mark in that set keep the monogram tile — inventing a logo
 * for a product that has its own would misidentify it.
 *
 * Run with: pnpm icons:providers
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

/** Harness id → the icon file that stands for that product. */
const MARKS = {
  // The burst, not the CLI's blocky tile: it is still legible at 14px.
  claude: "claude",
  codex: "codex",
  copilot: "copilot",
  cursor: "cursor",
  gemini: "gemini",
  kilocode: "kilocode",
  kimi: "kimi",
  kiro: "kiro",
  opencode: "opencode",
  qoder: "qoder",
  qwen: "qwen",
  trae: "trae",
};

/*
 * Brand colours, but only where the colour is part of recognising the product
 * *and* still reads on a dark surface. A mark with no entry here draws in the
 * colour of the row it sits in.
 */
const ACCENTS = {
  claude: "#d97757",
  gemini: "#8e75b2",
  qwen: "#6950ef",
  trae: "#32f08c",
};

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const iconDir = path.join(path.dirname(require.resolve("@lobehub/icons-static-svg/package.json")), "icons");
const out = path.join(root, "apps/desktop/src/renderer/src/lib/provider-marks.ts");

function readMark(id, slug) {
  const file = path.join(iconDir, `${slug}.svg`);
  const svg = readFileSync(file, "utf8");
  const title = /<title>([^<]*)<\/title>/u.exec(svg)?.[1] ?? slug;
  const body = svg.replace(/<title>[^<]*<\/title>/u, "");
  /*
   * Paths only. A mark that needs gradients or a clip path would need ids
   * unique to each rendered instance, so it is better off on the tile than
   * silently borrowing another instance's gradient.
   */
  const elements = [...body.matchAll(/<([a-zA-Z]+)/gu)].map((match) => match[1]);
  const unsupported = elements.filter((name) => name !== "svg" && name !== "path");
  if (unsupported.length > 0) {
    throw new Error(`${slug}.svg uses ${[...new Set(unsupported)].join(", ")}; only <path> is supported.`);
  }
  const paths = [...body.matchAll(/<path[^>]*\sd="([^"]+)"/gu)].map((match) => match[1]);
  if (paths.length === 0) throw new Error(`${slug}.svg has no path data.`);
  const viewBox = /viewBox="([^"]+)"/u.exec(svg)?.[1];
  if (viewBox !== "0 0 24 24") throw new Error(`${slug}.svg is ${viewBox}, not a 24x24 viewBox.`);
  return { id, title, paths, hex: ACCENTS[id] };
}

const entries = Object.entries(MARKS).map(([id, slug]) => readMark(id, slug));

const body = entries
  .map((entry) => {
    const hex = entry.hex ? `\n    hex: ${JSON.stringify(entry.hex)},` : "";
    return (
      `  ${JSON.stringify(entry.id)}: {\n` +
      `    title: ${JSON.stringify(entry.title)},${hex}\n` +
      `    paths: [\n${entry.paths.map((d) => `      ${JSON.stringify(d)},`).join("\n")}\n    ],\n` +
      `  },`
    );
  })
  .join("\n");

writeFileSync(
  out,
  `/*
 * Generated by scripts/generate-provider-icons.mjs. Do not edit by hand.
 *
 * Marks for the agent providers, on a 24x24 viewBox with the even-odd fill
 * rule. Drawn from the MIT-licensed @lobehub/icons-static-svg set (Copyright
 * (c) LobeHub). The trademarks belong to the products they identify; they
 * appear here to name the agent Capsule is talking to, nothing more.
 */

export interface ProviderMark {
  title: string;
  /** The brand colour, where it is part of recognising the product. */
  hex?: string;
  /** Path data for a 24x24 viewBox. */
  paths: string[];
}

export const PROVIDER_MARKS: Record<string, ProviderMark> = {
${body}
};
`,
  "utf8",
);
console.log(`Wrote ${entries.length} marks to ${path.relative(root, out)}`);
