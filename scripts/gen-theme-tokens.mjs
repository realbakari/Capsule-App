#!/usr/bin/env node
/*
 * Writes the theme token list and its JSON Schema from packages/ui/src/tokens.css,
 * so a theme file can name exactly the colours the interface reads.
 *
 * A token is themable when it is a colour in both appearances:
 *
 * - its `:root` value (dark) is a literal colour and the
 *   `html[data-theme="light"]` block sets it to a literal colour too, or
 * - its `:root` value is `light-dark(<light>, <dark>)` of two literal colours.
 *
 * Left out on purpose: aliases and mixes built from other tokens (`var(--base)`,
 * `color-mix(...)`), which follow their sources; values that are not colours
 * (shadows, sizes); and the component library's bare HSL channel triples,
 * which have no light value.
 *
 * Usage: node scripts/gen-theme-tokens.mjs [--check]
 * `--check` writes nothing and exits 1 when the committed files are stale.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const cssFile = path.join(root, "packages/ui/src/tokens.css");
const tsFile = path.join(root, "packages/shared/src/theme-tokens.ts");
const schemaFile = path.join(root, "schemas/theme.schema.json");
const SCHEMA_ID = "https://raw.githubusercontent.com/realbakari/Capsule-App/main/schemas/theme.schema.json";

const COLOUR = /^(#(?:[0-9a-f]{3}|[0-9a-f]{6}|[0-9a-f]{8})|(?:rgba?|hsla?|oklch)\([^()]*\))$/i;

function block(css, selector) {
  const start = css.search(new RegExp(`(^|\\n)${selector.replace(/[[\]"().]/g, "\\$&")}\\s*\\{`));
  if (start === -1) throw new Error(`tokens.css has no top-level ${selector} block`);
  const open = css.indexOf("{", start);
  const close = css.indexOf("}", open);
  const declarations = new Map();
  for (const part of css.slice(open + 1, close).split(";")) {
    const match = /^\s*--([a-z0-9-]+)\s*:\s*([\s\S]+?)\s*$/i.exec(part);
    if (match) declarations.set(match[1], match[2].replace(/\s+/g, " "));
  }
  return declarations;
}

function lightDark(value) {
  const match = /^light-dark\((.+)\)$/.exec(value);
  if (!match) return undefined;
  let depth = 0;
  for (let i = 0; i < match[1].length; i++) {
    const ch = match[1][i];
    if (ch === "(") depth++;
    else if (ch === ")") depth--;
    else if (ch === "," && depth === 0) return [match[1].slice(0, i).trim(), match[1].slice(i + 1).trim()];
  }
  return undefined;
}

function themableTokens(cssText) {
  const css = cssText.replace(/\/\*[\s\S]*?\*\//g, "");
  const dark = block(css, ":root");
  const light = block(css, 'html[data-theme="light"]');
  const tokens = [];
  for (const [name, value] of dark) {
    const pair = lightDark(value);
    if (pair && COLOUR.test(pair[0]) && COLOUR.test(pair[1])) {
      tokens.push({ name, light: pair[0], dark: pair[1] });
    } else if (COLOUR.test(value) && COLOUR.test(light.get(name) ?? "")) {
      tokens.push({ name, light: light.get(name), dark: value });
    }
  }
  return tokens;
}

function renderTs(tokens) {
  const record = (key) => tokens.map((t) => `    ${JSON.stringify(t.name)}: ${JSON.stringify(t[key])},`).join("\n");
  return `// Generated by scripts/gen-theme-tokens.mjs from packages/ui/src/tokens.css. Do not edit.

export const THEME_TOKENS = [
${tokens.map((t) => `  ${JSON.stringify(t.name)},`).join("\n")}
] as const;

export type ThemeToken = (typeof THEME_TOKENS)[number];

export const BUILTIN_TOKENS: { light: Record<ThemeToken, string>; dark: Record<ThemeToken, string> } = {
  light: {
${record("light")}
  },
  dark: {
${record("dark")}
  },
};
`;
}

const COLOUR_PATTERN =
  "^(#([0-9a-fA-F]{3}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})|(rgba?|hsla?|oklch)\\([0-9.,%\\s/+-]*(deg|turn|rad)?[0-9.,%\\s/+-]*\\))$";

/* The backdrop key's schema lives in TypeScript beside its parser; see gen-settings-schema.mjs for why it is bundled. */
async function backdropSchema() {
  const bundle = await build({
    stdin: { contents: 'export { BACKDROP_JSON_SCHEMA } from "./backdrop.js";', resolveDir: path.join(root, "packages/shared/src"), loader: "ts" },
    bundle: true,
    write: false,
    format: "esm",
    platform: "node",
    logLevel: "silent",
  });
  const module = await import(`data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].text).toString("base64")}`);
  return module.BACKDROP_JSON_SCHEMA;
}

async function renderSchema(tokens) {
  const colour = { type: "string", pattern: COLOUR_PATTERN };
  const syntax = tokens.filter((t) => t.name.startsWith("syntax-"));
  const schema = {
    $schema: "http://json-schema.org/draft-07/schema#",
    $id: SCHEMA_ID,
    title: "Capsule theme",
    type: "object",
    required: ["name", "appearance"],
    additionalProperties: false,
    properties: {
      $schema: { type: "string" },
      name: { type: "string", minLength: 1, maxLength: 80 },
      appearance: { enum: ["light", "dark"] },
      tokens: {
        type: "object",
        additionalProperties: false,
        properties: Object.fromEntries(
          tokens.map((t) => [t.name, { ...colour, description: `Light ${t.light}, dark ${t.dark}.` }]),
        ),
      },
      syntax: {
        type: "object",
        description: "Shorthand for the syntax-* tokens.",
        additionalProperties: false,
        properties: Object.fromEntries(syntax.map((t) => [t.name.slice("syntax-".length), colour])),
      },
      backdrop: await backdropSchema(),
    },
  };
  return `${JSON.stringify(schema, null, 2)}\n`;
}

function read(file) {
  try {
    return readFileSync(file, "utf8");
  } catch {
    return undefined;
  }
}

const tokens = themableTokens(readFileSync(cssFile, "utf8"));
const outputs = [
  [tsFile, renderTs(tokens)],
  [schemaFile, await renderSchema(tokens)],
];

if (process.argv.includes("--check")) {
  const stale = outputs.filter(([file, text]) => read(file) !== text).map(([file]) => path.relative(root, file));
  if (stale.length > 0) {
    console.error(`Theme tokens are out of date with packages/ui/src/tokens.css: ${stale.join(", ")}.`);
    console.error("Run node scripts/gen-theme-tokens.mjs and commit the result.");
    process.exit(1);
  }
} else {
  for (const [file, text] of outputs) {
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, text);
  }
  console.log(`Wrote ${tokens.length} theme tokens.`);
}
